/// Returns a `Command` for `limactl` with bundled-binary resolution and isolated `LIMA_HOME`,
/// via [`crate::binary::command`].
#[cfg(target_os = "macos")]
fn limactl_command() -> std::process::Command {
    crate::binary::command("limactl")
}

/// Netplan drop-in filename; presence marks a config that already carries the
/// VPN-aware provision script (see `lima_config` and lima-vm/lima#2984).
#[cfg(any(target_os = "macos", test))]
const LIMA_VPN_PROVISION_SENTINEL: &str = "99-speedwave-prefer-vznat.yaml";

/// Clock provision: Lima's SyncTime steps the guest clock every 10s (see `lima_config`).
#[cfg(any(target_os = "macos", test))]
const LIMA_TIMESYNC_PROVISION_SENTINEL: &str = "99-speedwave-no-settime.conf";

/// Returns `true` if the Lima config needs regenerating: VPN netplan drop-in missing, or
/// `memory`/`cpus` drifted from SSOT. Unparseable = no-drift (never touch a hand-mangled file).
#[cfg(any(target_os = "macos", test))]
pub fn lima_vm_config_needs_update(config_content: &str) -> bool {
    use crate::resources;
    let desired_gib = resources::desired_vm_memory_gib(resources::host_total_memory_gib());
    lima_vm_config_needs_update_with(config_content, desired_gib, desired_lima_vm_cpus())
}

/// Testable variant: compares config content against explicit desired memory + cpus.
#[cfg(any(target_os = "macos", test))]
pub fn lima_vm_config_needs_update_with(
    config_content: &str,
    desired_gib: u32,
    desired_cpus: u32,
) -> bool {
    // Trigger migration when either managed provision drop-in is absent — pre-update installs
    // need the netplan (lima-vm/lima#2984) and clock-step fixes injected on next boot.
    if !config_content.contains(LIMA_VPN_PROVISION_SENTINEL)
        || !config_content.contains(LIMA_TIMESYNC_PROVISION_SENTINEL)
    {
        return true;
    }
    // Whether a `prefix` line exists at all (regardless of parseability).
    let line_present = |prefix: &str| config_content.lines().any(|l| l.trim().starts_with(prefix));
    // Parse a `memory: "8GiB"` or `cpus: 4` value to u32; unparseable → None.
    let line_val = |prefix: &str| -> Option<u32> {
        config_content.lines().find_map(|line| {
            line.trim().strip_prefix(prefix).and_then(|rest| {
                let v = rest.trim().trim_matches('"').trim();
                v.strip_suffix("GiB").unwrap_or(v).parse::<u32>().ok()
            })
        })
    };
    // Regenerate if memory or cpus is absent or drifted; unparseable → no drift.
    let needs_update = |prefix: &str, desired: u32| -> bool {
        if !line_present(prefix) {
            return true; // line absent — regenerate to write the SSOT value
        }
        line_val(prefix).is_some_and(|current| current != desired)
    };
    needs_update("memory:", desired_gib) || needs_update("cpus:", desired_cpus)
}

/// Rewrites only the managed `memory:`/`cpus:` values in an existing lima.yaml, preserving every
/// other line (user mounts, disk size). `None` when a managed line is absent (caller falls back).
#[cfg(any(target_os = "macos", test))]
pub fn update_lima_managed_fields(
    content: &str,
    desired_gib: u32,
    desired_cpus: u32,
) -> Option<String> {
    let with_memory =
        rewrite_first_line(content, "memory:", &format!("memory: \"{desired_gib}GiB\""))?;
    rewrite_first_line(&with_memory, "cpus:", &format!("cpus: {desired_cpus}"))
}

/// Replaces the first line whose trimmed form starts with `prefix` (same match rule as the drift
/// check), keeping indentation and line ending. `None` if no line matches.
#[cfg(any(target_os = "macos", test))]
fn rewrite_first_line(content: &str, prefix: &str, replacement: &str) -> Option<String> {
    let mut replaced = false;
    let mut out = String::with_capacity(content.len() + 16);
    for line in content.split_inclusive('\n') {
        if !replaced && line.trim_start().starts_with(prefix) {
            let indent = &line[..line.len() - line.trim_start().len()];
            let ending = if line.ends_with("\r\n") {
                "\r\n"
            } else if line.ends_with('\n') {
                "\n"
            } else {
                ""
            };
            out.push_str(indent);
            out.push_str(replacement);
            out.push_str(ending);
            replaced = true;
        } else {
            out.push_str(line);
        }
    }
    replaced.then_some(out)
}

/// Updates the managed `memory`/`cpus` fields of `lima.yaml` (or regenerates from [`lima_config`]
/// if VPN netplan/a line is missing), restarts VM if running; no-op on no drift (ADR-068).
#[cfg(target_os = "macos")]
pub fn ensure_lima_vm_config() -> anyhow::Result<()> {
    use crate::binary;
    let data_dir = consts::data_dir();
    let source_template = data_dir.join("lima.yaml");

    // Fresh install — init_vm_macos will create it with correct config
    if !source_template.exists() {
        return Ok(());
    }

    let content = std::fs::read_to_string(&source_template)?;
    if !lima_vm_config_needs_update(&content) {
        return Ok(());
    }

    log::info!(
        "migrating Lima VM config to SSOT values (memory {}, cpus {}; host_ram/2 + host_cores/2)",
        desired_lima_vm_memory(),
        desired_lima_vm_cpus()
    );

    // Check if VM exists
    let list_output = limactl_command()
        .args(["list", "--format", "{{.Name}}"])
        .output()?;
    let list_str = String::from_utf8_lossy(&list_output.stdout);
    let vm_exists = list_str
        .lines()
        .any(|line| line.trim() == consts::lima_vm_name());

    // Stop VM if running
    if vm_exists {
        let status_output = limactl_command()
            .args(["list", "--format", "{{.Status}}", consts::lima_vm_name()])
            .output()?;
        let status_str = String::from_utf8_lossy(&status_output.stdout);
        if status_str.trim().eq_ignore_ascii_case("running") {
            log::warn!(
                "Stopping VM for memory migration — any running Claude sessions will be interrupted"
            );
            let timeout = std::time::Duration::from_secs(30);
            let mut stop_cmd = limactl_command();
            stop_cmd.args(["stop", consts::lima_vm_name()]);
            if let Err(e) = binary::run_with_timeout(&mut stop_cmd, timeout) {
                log::warn!("graceful stop failed ({e}), forcing stop");
                let mut force_cmd = limactl_command();
                force_cmd.args(["stop", "--force", consts::lima_vm_name()]);
                if let Err(e2) = binary::run_with_timeout(&mut force_cmd, timeout) {
                    log::warn!("forced stop also failed: {e2}, continuing with config update");
                }
            }
        }
    }

    // Surgical rewrite of the managed fields; full template regeneration only
    // when the VPN provision block or a managed line is missing.
    let desired_gib =
        crate::resources::desired_vm_memory_gib(crate::resources::host_total_memory_gib());
    let desired_cpus = desired_lima_vm_cpus();
    let (updated, surgical) = if content.contains(LIMA_VPN_PROVISION_SENTINEL)
        && content.contains(LIMA_TIMESYNC_PROVISION_SENTINEL)
    {
        match update_lima_managed_fields(&content, desired_gib, desired_cpus) {
            Some(u) => (u, true),
            None => {
                log::warn!(
                    "lima.yaml at {} has no managed memory/cpus lines — regenerating \
                     from the SSOT template; any manual edits are discarded",
                    source_template.display()
                );
                (lima_config(), false)
            }
        }
    } else {
        log::warn!(
            "lima.yaml at {} pre-dates a managed provision drop-in — regenerating \
             from the SSOT template; any manual edits are discarded",
            source_template.display()
        );
        (lima_config(), false)
    };
    std::fs::write(&source_template, &updated)?;

    // Update instance config too (may not exist if VM was never created).
    let instance_config = data_dir
        .join(consts::LIMA_SUBDIR)
        .join(consts::lima_vm_name())
        .join("lima.yaml");
    if instance_config.exists() {
        let instance_updated = if surgical {
            let instance_content = std::fs::read_to_string(&instance_config)?;
            update_lima_managed_fields(&instance_content, desired_gib, desired_cpus).unwrap_or_else(
                || {
                    log::warn!(
                        "instance lima.yaml at {} has no managed memory/cpus lines — \
                         replacing with the migrated source config",
                        instance_config.display()
                    );
                    updated.clone()
                },
            )
        } else {
            updated.clone()
        };
        std::fs::write(&instance_config, instance_updated)?;
    }

    // Restart VM if it existed
    if vm_exists {
        log::info!("Starting VM after memory migration");
        init_vm_macos()?;
    }

    log::info!("Lima VM config migration complete");
    Ok(())
}

/// Creates the Lima VM (if absent), starts it, and waits for containerd to be
/// ready inside it. Writes the SSOT `lima.yaml` on first run.
#[cfg(target_os = "macos")]
pub fn init_vm_macos() -> anyhow::Result<()> {
    // Ensure lima.yaml exists
    let data_dir = consts::data_dir();
    std::fs::create_dir_all(data_dir)?;
    let lima_config_path = data_dir.join("lima.yaml");
    if !lima_config_path.exists() {
        std::fs::write(&lima_config_path, lima_config())?;
    }

    // Check if Lima VM exists
    let list_output = limactl_command()
        .args(["list", "--format", "{{.Name}}"])
        .output()?;
    let list_str = String::from_utf8_lossy(&list_output.stdout);

    if !list_str
        .lines()
        .any(|line| line.trim() == consts::lima_vm_name())
    {
        // VM does not exist — create it
        let output = limactl_command()
            .args([
                "create",
                &format!("--name={}", consts::lima_vm_name()),
                "--tty=false",
            ])
            .arg(&lima_config_path)
            .output()?;
        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            anyhow::bail!("limactl create failed: {}", stderr.trim());
        }
    }

    // Start VM if not running
    let info_output = limactl_command()
        .args(["list", "--format", "{{.Status}}", consts::lima_vm_name()])
        .output()?;
    let status_str = String::from_utf8_lossy(&info_output.stdout);

    if !status_str.trim().eq_ignore_ascii_case("running") {
        // Provisioning-grade timeout: this start may first download the guest
        // nerdctl-full archive (first start under a newly bundled Lima).
        use crate::runtime::CommandRunner as _;
        let timeout = std::time::Duration::from_secs(consts::LIMA_VM_PROVISION_START_TIMEOUT_SECS);
        log::info!(
            "starting Lima VM '{}' — a one-time download of container tooling \
             (nerdctl-full) may run before boot (timeout: {}s)",
            consts::lima_vm_name(),
            timeout.as_secs()
        );
        crate::runtime::RealRunner
            .run_with_timeout("limactl", &["start", consts::lima_vm_name()], timeout)
            .map_err(|e| {
                anyhow::anyhow!(
                    "limactl start failed: {e}. {}",
                    consts::LIMA_START_PROVISION_HINT
                )
            })?;
    }

    // Wait for containerd to be ready inside VM (up to 30s)
    let mut ready = false;
    for _ in 0..15 {
        let verify = limactl_command()
            .args([
                "shell",
                consts::lima_vm_name(),
                "--",
                "sudo",
                "nerdctl",
                "info",
            ])
            .output()?;
        if verify.status.success() {
            ready = true;
            break;
        }
        std::thread::sleep(std::time::Duration::from_secs(2));
    }
    if !ready {
        anyhow::bail!(
            "containerd did not become ready inside VM after 30s. \
             Try running: limactl shell {} -- sudo nerdctl info",
            consts::lima_vm_name()
        );
    }

    Ok(())
}

