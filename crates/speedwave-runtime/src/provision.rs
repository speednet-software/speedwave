/// Maps the elevated-install PowerShell outcome to the bail message for `attempt_wsl_install`,
/// reporting a spawn/timeout distinctly from a genuine failed/cancelled install.
#[cfg(any(target_os = "windows", test))]
fn wsl_install_outcome_message(result: &anyhow::Result<std::process::ExitStatus>) -> anyhow::Error {
    match result {
        Err(e) => anyhow::anyhow!(
            "WSL2 installation is taking longer than expected ({e}); it may still be \
             running in the background under a separate elevated prompt. Wait for any \
             Windows Security / UAC prompt to finish, then run Speedwave setup again. \
             If no installation is in progress, see below.\n\
             {}",
            consts::WSL_NOT_AVAILABLE_MSG
        ),
        Ok(status) if !status.success() => anyhow::anyhow!(
            "WSL2 installation failed or was cancelled.\n\
             {}",
            consts::WSL_NOT_AVAILABLE_MSG
        ),
        Ok(_) => anyhow::anyhow!(
            "WSL2 has been installed. Please restart your computer and run Speedwave setup again."
        ),
    }
}

/// Installs WSL2 via elevated PowerShell. Always bails: either with a restart
/// prompt (success), a timeout notice (install may still be running), or a
/// failure message.
#[cfg(target_os = "windows")]
fn attempt_wsl_install() -> anyhow::Result<()> {
    let result = crate::binary::run_powershell(
        &[
            "-Command",
            "Start-Process wsl.exe -ArgumentList '--install','--no-distribution' -Verb RunAs -Wait",
        ],
        std::time::Duration::from_secs(900),
    );
    Err(wsl_install_outcome_message(&result))
}

/// Downloads the Ubuntu rootfs (SHA256-verified) and imports it as a dedicated WSL2 distribution:
/// bundled rootfs first (offline install), then cached download, then fresh download.
#[cfg(target_os = "windows")]
fn import_wsl_distro() -> anyhow::Result<()> {
    use crate::runtime::decode_wsl_output;

    let data_dir = consts::data_dir();
    let wsl_dir = data_dir.join("wsl");
    let rootfs_path = wsl_dir.join("ubuntu-rootfs.tar.gz");
    std::fs::create_dir_all(&wsl_dir)?;

    let (rootfs_url, expected_sha256) = wsl_rootfs_for_arch()?;

    // Try bundled rootfs first (offline install from NSIS bundle)
    let mut have_valid_rootfs = false;

    if let Some(bundled) = crate::bundle::find_bundled_asset(crate::bundle::UBUNTU_ROOTFS_ASSET) {
        match verify_sha256_ps(&bundled, expected_sha256) {
            Ok(true) => {
                // Copy bundled rootfs to the cache location for wsl --import
                std::fs::copy(&bundled, &rootfs_path)?;
                have_valid_rootfs = true;
            }
            Ok(false) => {
                log::warn!(
                    "bundled Ubuntu rootfs at {} does not match the pinned SHA256; \
                     falling back to download",
                    bundled.display()
                );
            }
            Err(e) => log::warn!(
                "could not verify bundled Ubuntu rootfs at {} ({e}); falling back to download",
                bundled.display()
            ),
        }
    }

    // Check cached download
    if !have_valid_rootfs && rootfs_path.exists() {
        match verify_sha256_ps(&rootfs_path, expected_sha256) {
            Ok(true) => have_valid_rootfs = true,
            Ok(false) => {
                log::warn!(
                    "cached Ubuntu rootfs at {} does not match the pinned SHA256; \
                     re-downloading",
                    rootfs_path.display()
                );
                let _ = std::fs::remove_file(&rootfs_path);
            }
            Err(e) => {
                // Verification didn't complete (e.g. AV-scan slowdown on a large file);
                // keep the cached file on disk and fall through to a fresh download.
                log::warn!(
                    "could not verify cached Ubuntu rootfs at {} ({e}); re-downloading",
                    rootfs_path.display()
                );
            }
        }
    }

    // Fall back to download
    if !have_valid_rootfs {
        let escaped_rootfs = ps_escape(&rootfs_path);
        let download_and_verify = format!(
            "$ProgressPreference = 'SilentlyContinue'; \
             Invoke-WebRequest -Uri '{}' -OutFile '{}'; \
             $hash = (Get-FileHash -Path '{}' -Algorithm SHA256).Hash.ToLower(); \
             if ($hash -ne '{}') {{ \
                 Remove-Item '{}' -Force; \
                 Write-Error \"SHA256 mismatch: expected {}, got $hash\"; \
                 exit 1 \
             }}",
            rootfs_url,
            escaped_rootfs,
            escaped_rootfs,
            expected_sha256,
            escaped_rootfs,
            expected_sha256
        );
        let download = crate::binary::run_powershell(
            &["-NoProfile", "-Command", &download_and_verify],
            std::time::Duration::from_secs(1800),
        )?;
        if !download.success() {
            anyhow::bail!(
                "Failed to download or verify Ubuntu rootfs for WSL2 \
                 (expected SHA256: {})",
                expected_sha256
            );
        }
    }

    let install_dir = wsl_dir.join(consts::wsl_distro_name());
    std::fs::create_dir_all(&install_dir)?;
    let status = crate::binary::system_command("wsl.exe")
        .args([
            "--import",
            consts::wsl_distro_name(),
            &install_dir.to_string_lossy(),
            &rootfs_path.to_string_lossy(),
        ])
        .status()?;
    if !status.success() {
        // Check if the distro was already registered (import failed because it exists)
        let recheck = crate::binary::system_command("wsl.exe")
            .args(["--list", "--quiet"])
            .output()?;
        let recheck_str = decode_wsl_output(&recheck.stdout);
        if recheck_str
            .lines()
            .any(|l| l.trim().trim_matches('\0') == consts::wsl_distro_name())
        {
            // Distro exists but we didn't create it — verify it's ours.
            verify_wsl_distro_origin()?;
            log::warn!(
                "WSL2 import failed but distro '{}' already exists and is verified — continuing",
                consts::wsl_distro_name()
            );
        } else {
            anyhow::bail!("Failed to import Speedwave WSL2 distribution");
        }
    }

    // Import path: safe to terminate (no containers yet); Err retried by IfIdle on next launch (ADR-052).
    use anyhow::Context as _;
    ensure_wsl_distro_metadata(TerminateOnChange::Yes)
        .context("configuring the imported WSL distro's automount failed")?;

    Ok(())
}

/// Whether `ensure_wsl_distro_metadata` may `wsl --terminate` to apply the change.
#[cfg(any(target_os = "windows", test))]
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum TerminateOnChange {
    /// Import path: no container runs yet, so terminating is always safe.
    Yes,
    /// Startup/post-update: terminate only when idle, else uid-1000 EACCES (ADR-052).
    IfIdle,
}

/// Pure terminate policy (testable without Windows); `has_running` only for `IfIdle`.
#[cfg(any(target_os = "windows", test))]
pub fn terminate_decision(terminate: TerminateOnChange, has_running: bool) -> bool {
    match terminate {
        TerminateOnChange::Yes => true,
        TerminateOnChange::IfIdle => !has_running,
    }
}

/// Unwraps a `read_wsl_conf` result, warning before degrading an `Err` (real
/// spawn/IO failure) to empty rather than bailing (ADR-052).
#[cfg(any(target_os = "windows", test))]
pub fn wsl_conf_or_warn(read: anyhow::Result<String>, distro: &str, when: &str) -> String {
    match read {
        Ok(content) => content,
        Err(e) => {
            log::warn!("failed to read wsl.conf for {distro} ({when}); treating as empty: {e}");
            String::new()
        }
    }
}

/// Sets `/etc/wsl.conf` automount (`Yes` at import, `IfIdle` at startup; `Err` if the write didn't land — ADR-052).
#[cfg(target_os = "windows")]
pub fn ensure_wsl_distro_metadata(terminate: TerminateOnChange) -> anyhow::Result<()> {
    let distro = consts::wsl_distro_name();
    let opts = consts::wsl_automount_options();
    let (uid, _gid) = consts::container_uid_gid();

    let existing = wsl_conf_or_warn(read_wsl_conf(distro), distro, "initial read");
    let updated = merge_wsl_conf_automount(&existing, &opts);

    if updated == existing {
        log::debug!("automount options already current in {distro}");
        return Ok(());
    }

    write_wsl_conf(distro, &updated)?;

    // Verify the change landed; a read-only wsl.conf silently fails otherwise.
    let verify = wsl_conf_or_warn(read_wsl_conf(distro), distro, "post-write verify");
    if !wsl_conf_automount_has_uid(&verify, uid) {
        anyhow::bail!(
            "wrote /etc/wsl.conf for {distro} but uid={uid} is NOT present on re-read; \
             the uid-1000 container will hit EACCES on the drvfs mount and fail to start \
             (login/onboarding broken). Check that /etc/wsl.conf is writable as root"
        );
    }

    // Probe lazily (only IfIdle, only now that a real change exists) then decide.
    let has_running =
        matches!(terminate, TerminateOnChange::IfIdle) && wsl_distro_has_running_containers(distro);
    if terminate_decision(terminate, has_running) {
        let terminated = crate::binary::system_command("wsl.exe")
            .args(["--terminate", distro])
            .status()
            .map(|s| s.success())
            .unwrap_or(false);
        if terminated {
            log::info!("enabled metadata automount for {distro} (terminated to apply)");
        } else {
            log::warn!(
                "wrote metadata automount for {distro} but `wsl --terminate` failed; \
                 applies on next WSL restart"
            );
        }
    } else {
        log::info!(
            "enabled metadata automount for {distro} (containers running; \
             applies on next WSL restart)"
        );
    }
    Ok(())
}

/// Reads `/etc/wsl.conf` as root; `Ok("")` if absent, `Err` only on spawn failure.
#[cfg(target_os = "windows")]
fn read_wsl_conf(distro: &str) -> anyhow::Result<String> {
    let out = crate::binary::system_command("wsl.exe")
        .args(["-d", distro, "-u", "root", "--", "cat", "/etc/wsl.conf"])
        .output()?;
    // `cat` on a missing file exits non-zero — treat that as empty, not an error.
    Ok(if out.status.success() {
        String::from_utf8_lossy(&out.stdout).into_owned()
    } else {
        String::new()
    })
}

/// Writes `content` to `/etc/wsl.conf` via `tee` (stdin), as root in the distro.
#[cfg(target_os = "windows")]
fn write_wsl_conf(distro: &str, content: &str) -> anyhow::Result<()> {
    use std::io::Write;
    use std::process::Stdio;
    let mut child = crate::binary::system_command("wsl.exe")
        .args(["-d", distro, "-u", "root", "--", "tee", "/etc/wsl.conf"])
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or_else(|| anyhow::anyhow!("failed to open stdin for tee /etc/wsl.conf"))?
        .write_all(content.as_bytes())?;
    let status = child.wait()?;
    if !status.success() {
        anyhow::bail!("`tee /etc/wsl.conf` exited with {status} in {distro}");
    }
    Ok(())
}

/// `true` if any container runs in the distro (containerd-down ⇒ idle; spawn failure ⇒ fail-safe busy).
#[cfg(target_os = "windows")]
fn wsl_distro_has_running_containers(distro: &str) -> bool {
    // Session is already `-u root`, so no `sudo` (not always in root's PATH).
    let out = crate::binary::system_command("wsl.exe")
        .args(["-d", distro, "-u", "root", "--", "nerdctl", "ps", "-q"])
        .output();
    match out {
        Ok(o) => running_containers_from_probe(
            o.status.success(),
            &String::from_utf8_lossy(&o.stdout),
            &String::from_utf8_lossy(&o.stderr),
        ),
        Err(e) => {
            log::warn!("spawn failed probing running containers for {distro}; assuming busy: {e}");
            true
        }
    }
}

/// Interprets a `nerdctl ps -q` probe: running, idle, or (on containerd-down stderr) idle; else fail-safe busy.
#[cfg(any(target_os = "windows", test))]
pub fn running_containers_from_probe(success: bool, stdout: &str, stderr: &str) -> bool {
    if success {
        return !stdout.trim().is_empty();
    }
    let lower = stderr.to_ascii_lowercase();
    let daemon_down = lower.contains("connection refused")
        || lower.contains("cannot connect")
        || lower.contains("failed to connect")
        || lower.contains("no such file or directory") // containerd.sock absent
        || lower.contains("is the containerd daemon running");
    if daemon_down {
        false // daemon not up ⇒ nothing running ⇒ idle
    } else {
        log::warn!("nerdctl ps failed (assuming busy): {stderr}");
        true
    }
}

/// `true` if `[automount].options` contains `uid={uid}` as a full token (anchored, not substring).
#[cfg(any(target_os = "windows", test))]
pub fn wsl_conf_automount_has_uid(content: &str, uid: u32) -> bool {
    automount_options_line(content).is_some_and(|opts| options_has_uid(opts, uid))
}

/// Value of the `options =` key in the first `[automount]` section (comments ignored); `None` if absent.
#[cfg(any(target_os = "windows", test))]
pub fn automount_options_line(content: &str) -> Option<&str> {
    let mut in_automount = false;
    for raw in content.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(sec) = line.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            in_automount = sec.trim().eq_ignore_ascii_case("automount");
            continue;
        }
        if in_automount {
            if let Some((k, v)) = line.split_once('=') {
                if k.trim().eq_ignore_ascii_case("options") {
                    return Some(v.trim().trim_matches('"'));
                }
            }
        }
    }
    None
}

/// `true` if a comma-separated options string contains `uid={uid}` as a whole token.
#[cfg(any(target_os = "windows", test))]
pub fn options_has_uid(options: &str, uid: u32) -> bool {
    let needle = format!("uid={uid}");
    options.split(',').any(|tok| tok.trim() == needle)
}

/// Sets `[automount].options` to `opts`, replacing only that key; all other keys/sections preserved. CRLF-aware, idempotent.
#[cfg(any(target_os = "windows", test))]
pub fn merge_wsl_conf_automount(input: &str, opts: &str) -> String {
    let nl = if input.contains("\r\n") { "\r\n" } else { "\n" };
    let mut out = String::with_capacity(input.len() + 64);
    // `Some(true)` = first [automount]; `Some(false)` = duplicate (dropped); `None` = other.
    let mut in_automount: Option<bool> = None;
    let mut automount_seen = false;
    let mut options_written = false;

    for line in input.split_inclusive('\n') {
        let trimmed = line.trim();
        if let Some(sec) = trimmed
            .strip_prefix('[')
            .and_then(|s| s.strip_suffix(']'))
            .map(|s| s.trim().to_ascii_lowercase())
        {
            if sec == "automount" {
                if automount_seen {
                    in_automount = Some(false); // duplicate — drop header + body
                    continue;
                }
                automount_seen = true;
                in_automount = Some(true);
                out.push_str(line);
                // Emit our options line right after the first header.
                let line_nl = if line.ends_with('\n') { nl } else { "" };
                out.push_str(&format!("options = \"{opts}\"{line_nl}"));
                options_written = true;
                continue;
            }
            in_automount = None;
            out.push_str(line);
            continue;
        }
        match in_automount {
            // First [automount] body: drop only the old options line, keep the rest.
            Some(true) => {
                let is_options = trimmed
                    .split_once('=')
                    .is_some_and(|(k, _)| k.trim().eq_ignore_ascii_case("options"));
                if !is_options {
                    out.push_str(line);
                }
            }
            // Duplicate [automount] body — drop entirely.
            Some(false) => {}
            None => out.push_str(line),
        }
    }

    if !options_written {
        // No [automount] section existed — append a fresh one.
        if !out.is_empty() && !out.ends_with('\n') {
            out.push_str(nl);
        }
        out.push_str(&format!("[automount]{nl}options = \"{opts}\"{nl}"));
    }
    out
}

/// `true` if a `nerdctl --version` line reports exactly `NERDCTL_FULL_VERSION`.
/// Output shape is `nerdctl version 2.2.2` (tokens after "version").
#[cfg(any(target_os = "windows", test))]
fn nerdctl_version_matches_pin(version_line: &str) -> bool {
    version_line
        .split_whitespace()
        .any(|tok| tok == consts::NERDCTL_FULL_VERSION)
}

/// `true` when a failed version probe means nerdctl is genuinely absent (vs a
/// transient wsl.exe transport error that must not trigger reinstall).
#[cfg(any(target_os = "windows", test))]
fn probe_indicates_absent(code: Option<i32>, stderr: &str) -> bool {
    code == Some(127) || stderr.contains("not found") || stderr.contains("No such file")
}

/// In-process half of the nerdctl install lock; the cross-process half is the
/// `<data_dir>/nerdctl-install.lock` file (see [`with_nerdctl_install_lock_in`]).
#[cfg(any(target_os = "windows", test))]
static NERDCTL_INSTALL_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

/// Serializes the nerdctl ensure/install sequence across processes (Desktop `ensure_ready` + CLI
/// startup); loser re-probes the pin under lock (`install_nerdctl_full` step 1), skips if aligned.
#[cfg(any(target_os = "windows", test))]
fn with_nerdctl_install_lock_in<F, T>(data_dir: &std::path::Path, f: F) -> anyhow::Result<T>
where
    F: FnOnce() -> anyhow::Result<T>,
{
    let lock_path = data_dir.join(consts::NERDCTL_INSTALL_LOCK_FILE);
    crate::runtime::compose_locks::with_file_lock_in(&NERDCTL_INSTALL_LOCK, &lock_path, f)
}

/// Persisted download-backoff marker (`consts::NERDCTL_DOWNLOAD_BACKOFF_FILE`); written after a
/// failed download so short-lived CLI processes back off instead of retrying every invocation.
#[cfg(any(target_os = "windows", test))]
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
struct NerdctlDownloadBackoff {
    /// Unix epoch seconds of the last failed download attempt.
    last_failure_epoch_secs: u64,
    /// Count of consecutive failed download attempts.
    consecutive_failures: u32,
}

/// Current Unix time in whole seconds (0 on a pre-epoch clock).
#[cfg(any(target_os = "windows", test))]
fn epoch_secs_now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// `true` when the last download failure is recent enough to skip a retry.
#[cfg(any(target_os = "windows", test))]
fn download_backoff_active(state: Option<&NerdctlDownloadBackoff>, now_epoch_secs: u64) -> bool {
    state.is_some_and(|s| {
        now_epoch_secs.saturating_sub(s.last_failure_epoch_secs)
            < consts::NERDCTL_DOWNLOAD_RETRY_DELAY_SECS
    })
}

/// Loads the backoff marker; absent or unparseable → `None` (treated as fresh).
#[cfg(any(target_os = "windows", test))]
fn load_download_backoff(path: &std::path::Path) -> Option<NerdctlDownloadBackoff> {
    let data = std::fs::read_to_string(path).ok()?;
    serde_json::from_str(&data).ok()
}

/// Records a failed download attempt (state-change log; best-effort persist).
#[cfg(any(target_os = "windows", test))]
fn record_download_failure(path: &std::path::Path, now_epoch_secs: u64) {
    let state = NerdctlDownloadBackoff {
        last_failure_epoch_secs: now_epoch_secs,
        consecutive_failures: load_download_backoff(path)
            .map_or(1, |prev| prev.consecutive_failures.saturating_add(1)),
    };
    let write = serde_json::to_string(&state)
        .map_err(anyhow::Error::from)
        .and_then(|json| {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)?;
            }
            std::fs::write(path, json).map_err(anyhow::Error::from)
        });
    match write {
        Ok(()) => log::warn!(
            "nerdctl-full download failed ({} consecutive failure(s)); \
             next retry no sooner than {}s from now",
            state.consecutive_failures,
            consts::NERDCTL_DOWNLOAD_RETRY_DELAY_SECS
        ),
        Err(e) => log::warn!("could not persist nerdctl download backoff marker: {e}"),
    }
}

/// Removes the backoff marker; logs only when a marker actually existed.
#[cfg(any(target_os = "windows", test))]
fn clear_download_backoff(path: &std::path::Path) {
    match std::fs::remove_file(path) {
        Ok(()) => log::info!("cleared nerdctl download backoff after successful alignment"),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => log::warn!("could not remove nerdctl download backoff marker: {e}"),
    }
}

/// Waits for `child` (piped stdout/stderr) at most `timeout`, draining pipes
/// on threads; kills the child and errors on expiry.
#[cfg(any(target_os = "windows", test))]
fn wait_with_output_timeout(
    mut child: std::process::Child,
    timeout: std::time::Duration,
) -> anyhow::Result<std::process::Output> {
    fn drain<R: std::io::Read + Send + 'static>(
        pipe: Option<R>,
    ) -> std::thread::JoinHandle<Vec<u8>> {
        std::thread::spawn(move || {
            let mut buf = Vec::new();
            if let Some(mut r) = pipe {
                let _ = r.read_to_end(&mut buf);
            }
            buf
        })
    }
    let stdout = drain(child.stdout.take());
    let stderr = drain(child.stderr.take());
    let start = std::time::Instant::now();
    let status = loop {
        match child.try_wait()? {
            Some(status) => break status,
            None if start.elapsed() >= timeout => {
                if let Err(e) = child.kill() {
                    log::warn!("failed to kill timed-out child process: {e}");
                }
                let _ = child.wait();
                anyhow::bail!("child process timed out after {}s", timeout.as_secs());
            }
            None => std::thread::sleep(std::time::Duration::from_millis(200)),
        }
    };
    Ok(std::process::Output {
        status,
        stdout: stdout.join().unwrap_or_default(),
        stderr: stderr.join().unwrap_or_default(),
    })
}

#[cfg(target_os = "windows")]
fn install_nerdctl_full() -> anyhow::Result<()> {
    let nerdctl_check = crate::binary::system_command("wsl.exe")
        .args([
            "-d",
            consts::wsl_distro_name(),
            "--",
            "nerdctl",
            "--version",
        ])
        .output()?;
    let backoff_path = consts::data_dir().join(consts::NERDCTL_DOWNLOAD_BACKOFF_FILE);
    let drift = if nerdctl_check.status.success() {
        let version_line = String::from_utf8_lossy(&nerdctl_check.stdout);
        if nerdctl_version_matches_pin(&version_line) {
            // Already aligned (possibly by the other lock holder) — drop any stale backoff.
            clear_download_backoff(&backoff_path);
            return Ok(());
        }
        format!(
            "in-distro nerdctl is not the pinned {} (got: {})",
            consts::NERDCTL_FULL_VERSION,
            version_line.trim()
        )
    } else {
        // Probe failed: distinguish genuinely-absent from a transient transport error.
        let stderr = String::from_utf8_lossy(&nerdctl_check.stderr);
        let absent = probe_indicates_absent(nerdctl_check.status.code(), &stderr);
        if !absent {
            anyhow::bail!(
                "nerdctl version probe failed transiently (status {:?}: {}); skipping reinstall",
                nerdctl_check.status.code(),
                stderr.trim()
            );
        }
        format!(
            "in-distro nerdctl absent; need {}",
            consts::NERDCTL_FULL_VERSION
        )
    };

    // Try bundled nerdctl-full tarball first (offline install from the bundle).
    let expected_sha256 = nerdctl_sha256_for_arch()?;
    let mut bundled_wsl_path: Option<String> = None;
    let mut bundled_rejected: Option<(PathBuf, String)> = None;

    if let Some(bundled) = crate::bundle::find_bundled_asset(crate::bundle::NERDCTL_TARBALL_ASSET) {
        match verify_sha256_ps(&bundled, expected_sha256) {
            Ok(true) => {
                // Translate the bundled tarball's host path to WSL via the SSOT.
                match crate::engine_path::to_engine_path(&bundled) {
                    Ok(wsl) => bundled_wsl_path = Some(wsl),
                    Err(e) => log::warn!(
                        "could not translate bundled nerdctl path to WSL ({e}); will download instead"
                    ),
                }
            }
            Ok(false) => {
                bundled_rejected = Some((bundled, "does not match the pinned SHA256".to_string()))
            }
            Err(e) => bundled_rejected = Some((bundled, format!("could not be verified ({e})"))),
        }
    }

    // Download path only: back off after a recent failure instead of re-pulling
    // the full archive on every CLI invocation (state-change logging only).
    let downloading = bundled_wsl_path.is_none();
    if downloading
        && download_backoff_active(
            load_download_backoff(&backoff_path).as_ref(),
            epoch_secs_now(),
        )
    {
        log::debug!(
            "{drift}; skipping download retry (recent failure, retry delay {}s)",
            consts::NERDCTL_DOWNLOAD_RETRY_DELAY_SECS
        );
        return Ok(());
    }
    if let Some((rejected, reason)) = bundled_rejected {
        log::warn!(
            "bundled nerdctl tarball at {} {reason} (pinned {}); \
             falling back to in-distro download",
            rejected.display(),
            consts::NERDCTL_FULL_VERSION
        );
    }
    if downloading {
        log::info!(
            "{drift}; downloading nerdctl-full {} inside the distro (large archive, bounded by {}s)",
            consts::NERDCTL_FULL_VERSION,
            consts::NERDCTL_DOWNLOAD_MAX_TIME_SECS
        );
    } else {
        log::info!(
            "{drift}; installing {} from the bundled tarball",
            consts::NERDCTL_FULL_VERSION
        );
    }

    // Build install script: use bundled file if available, otherwise download
    let source_commands = if let Some(ref wsl_path) = bundled_wsl_path {
        let escaped = wsl_path.replace('\'', "'\\''");
        format!(
            "mkdir -p /tmp/nerdctl-install\ncp '{}' \"/tmp/nerdctl-install/${{TARBALL}}\"",
            escaped
        )
    } else {
        format!(
            "mkdir -p /tmp/nerdctl-install\ncurl -fsSL --connect-timeout {} --max-time {} \"$URL\" -o \"/tmp/nerdctl-install/${{TARBALL}}\"",
            consts::NERDCTL_DOWNLOAD_CONNECT_TIMEOUT_SECS,
            consts::NERDCTL_DOWNLOAD_MAX_TIME_SECS
        )
    };

    let install_script = format!(
        r#"set -e
ARCH=$(uname -m)
case "$ARCH" in
  x86_64) ARCH="amd64"; EXPECTED="{sha256_amd64}" ;;
  aarch64) ARCH="arm64"; EXPECTED="{sha256_arm64}" ;;
  *) echo "Unsupported architecture: $ARCH"; exit 1 ;;
esac
VERSION="{version}"
TARBALL="nerdctl-full-${{VERSION}}-linux-${{ARCH}}.tar.gz"
URL="https://github.com/containerd/nerdctl/releases/download/v${{VERSION}}/${{TARBALL}}"
{source_commands}
ACTUAL=$(sha256sum "/tmp/nerdctl-install/${{TARBALL}}" | awk '{{print $1}}')
if [ "$EXPECTED" != "$ACTUAL" ]; then
  echo "SHA256 MISMATCH: expected $EXPECTED, got $ACTUAL"
  rm -rf /tmp/nerdctl-install
  exit 1
fi
# Patch KillMode=process via override BEFORE stop so containers survive the
# upgrade (stopping a unit without it cgroup-kills them). No-op on fresh install.
if [ -f /etc/systemd/system/containerd.service ]; then
  mkdir -p /etc/systemd/system/containerd.service.d
  printf '[Service]\nKillMode=process\nDelegate=yes\n' > /etc/systemd/system/containerd.service.d/10-speedwave-killmode.conf
  command -v systemctl >/dev/null 2>&1 && systemctl daemon-reload 2>/dev/null || true
fi
# Stop daemons before unpacking — tar over live binaries fails ETXTBSY (ADR-072).
# pkill covers the `$exec &` non-systemd fallback. No-op on fresh install.
command -v systemctl >/dev/null 2>&1 && systemctl stop buildkit containerd 2>/dev/null || true
pkill -x buildkitd 2>/dev/null || true
pkill -x containerd 2>/dev/null || true
tar -C /usr/local --unlink-first --recursive-unlink -xzf "/tmp/nerdctl-install/${{TARBALL}}"
rm -rf /tmp/nerdctl-install
# Install iptables — required by CNI bridge plugin for container networking.
# nerdctl-full bundles CNI plugins but iptables is a system dependency.
if ! command -v iptables >/dev/null 2>&1; then
  apt-get update -qq && apt-get install -y -qq iptables >/dev/null
fi
# install_service NAME EXEC AFTER REQUIRES CHECK_CMD [CHECK_ARGS...]
# Installs a systemd service unit file, starts it, and waits up to 30s for readiness.
install_service() {{
  local name="$1" exec="$2" after="$3" requires="$4"
  shift 4
  local check_cmd="$@"
  mkdir -p /etc/systemd/system
  cat > "/etc/systemd/system/${{name}}.service" <<UNIT
[Unit]
Description=${{name}} daemon
${{after:+After=$after}}
${{requires:+Requires=$requires}}
[Service]
ExecStart=$exec
Restart=always
KillMode=process
Delegate=yes
[Install]
WantedBy=multi-user.target
UNIT
  # Try systemd unconditionally — gating on overall system state skips unit
  # installation forever on the common WSL2 `degraded` state.
  if command -v systemctl >/dev/null 2>&1 \
     && systemctl daemon-reload >/dev/null 2>&1 \
     && systemctl enable --now "$name" >/dev/null 2>&1; then
    :
  else
    # Detach from inherited stdio — daemons holding the caller's pipes would
    # block the host's wait_with_output() forever (post-upgrade hang).
    setsid $exec </dev/null >>"/var/log/${{name}}.log" 2>&1 &
  fi
  for i in $(seq 1 15); do
    if $check_cmd >/dev/null 2>&1; then return 0; fi
    sleep 2
  done
  echo "$name did not become ready after 30s" >&2
  exit 1
}}
# Configure containerd as a system service so it starts on every WSL session
install_service containerd /usr/local/bin/containerd network.target "" nerdctl info
# Start buildkitd — required for `nerdctl build` (image building).
# On WSL2 we run as root (not rootless), so install as a systemd system service.
install_service buildkit "/usr/local/bin/buildkitd --oci-worker=false --containerd-worker=true" containerd.service containerd.service buildctl debug workers
"#,
        version = consts::NERDCTL_FULL_VERSION,
        sha256_amd64 = consts::NERDCTL_FULL_SHA256_AMD64,
        sha256_arm64 = consts::NERDCTL_FULL_SHA256_ARM64,
        source_commands = source_commands
    );
    // Write the install script via stdin to avoid wsl.exe arg length/escaping.
    let mut child = crate::binary::system_command("wsl.exe")
        .args(["-d", consts::wsl_distro_name(), "--", "bash", "-s"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()?;
    use std::io::Write;
    if let Some(mut stdin) = child.stdin.take() {
        stdin.write_all(install_script.as_bytes())?;
        // Drop stdin to close the pipe and let bash finish
    }
    // Bounded host-side wait — a stalled in-distro download must not hang startup.
    let output = match wait_with_output_timeout(
        child,
        std::time::Duration::from_secs(consts::NERDCTL_INSTALL_TIMEOUT_SECS),
    ) {
        Ok(output) => output,
        Err(e) => {
            if downloading {
                record_download_failure(&backoff_path, epoch_secs_now());
            }
            return Err(e);
        }
    };
    if !output.status.success() {
        if downloading {
            record_download_failure(&backoff_path, epoch_secs_now());
        }
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        log::error!(
            "nerdctl-full install failed (exit {}): stdout={}, stderr={}",
            output.status,
            stdout.trim(),
            stderr.trim()
        );
        anyhow::bail!(
            "Failed to install nerdctl-full inside {} WSL2 distribution: {}",
            consts::wsl_distro_name(),
            stderr.trim()
        );
    }

    clear_download_backoff(&backoff_path);
    Ok(())
}

/// Reinstalls the in-distro nerdctl if it drifted from the pin (ADR-072). Warn-only,
/// once-per-process; Desktop and CLI serialize on the cross-process lock, loser re-probes under it.
#[cfg(target_os = "windows")]
pub fn ensure_nerdctl_version() {
    use std::sync::Once;
    static ONCE: Once = Once::new();
    ONCE.call_once(|| {
        let result = with_nerdctl_install_lock_in(consts::data_dir(), install_nerdctl_full);
        if let Err(e) = result {
            log::warn!("could not align in-distro nerdctl to the pin: {e}");
        }
    });
}

/// No-op off Windows: macOS gets nerdctl from Lima (`.lima-version`).
#[cfg(not(target_os = "windows"))]
pub fn ensure_nerdctl_version() {}

/// One-stop Windows invariants for every engine consumer (Desktop AND CLI): nerdctl pin, drvfs
/// metadata automount (uid=1000, ADR-052), `.wslconfig` VPN-compat keys. Warn-only.
#[cfg(target_os = "windows")]
pub fn ensure_windows_invariants() {
    ensure_nerdctl_version();
    use std::sync::Once;
    static ONCE: Once = Once::new();
    ONCE.call_once(|| {
        if let Err(e) = ensure_wsl_distro_metadata(TerminateOnChange::IfIdle) {
            log::warn!("could not verify drvfs metadata automount: {e}");
        }
        if let Err(e) = ensure_wslconfig_vpn_compat() {
            log::warn!("could not verify .wslconfig VPN compat: {e}");
        }
    });
}

