/// Escapes a path for safe interpolation inside PowerShell single-quoted strings.
/// PowerShell single-quoted strings only require doubling of single quotes.
#[cfg(target_os = "windows")]
fn ps_escape(path: &std::path::Path) -> String {
    path.display().to_string().replace('\'', "''")
}

/// Selects the rootfs URL and SHA256 hash for the current host architecture.
#[cfg(target_os = "windows")]
fn wsl_rootfs_for_arch() -> anyhow::Result<(&'static str, &'static str)> {
    match std::env::consts::ARCH {
        "x86_64" => Ok((
            consts::WSL_ROOTFS_URL_AMD64,
            consts::WSL_ROOTFS_SHA256_AMD64,
        )),
        "aarch64" => Ok((
            consts::WSL_ROOTFS_URL_ARM64,
            consts::WSL_ROOTFS_SHA256_ARM64,
        )),
        arch => anyhow::bail!("Unsupported architecture for WSL2 rootfs: {}", arch),
    }
}

/// Selects the nerdctl-full SHA256 hash for the current host architecture.
#[cfg(target_os = "windows")]
fn nerdctl_sha256_for_arch() -> anyhow::Result<&'static str> {
    match std::env::consts::ARCH {
        "x86_64" => Ok(consts::NERDCTL_FULL_SHA256_AMD64),
        "aarch64" => Ok(consts::NERDCTL_FULL_SHA256_ARM64),
        arch => anyhow::bail!("Unsupported architecture for nerdctl-full: {}", arch),
    }
}

/// Verifies SHA256 of a file using PowerShell. `Ok(bool)` is a real match/mismatch;
/// `Err` (spawn failure or timeout) is not a mismatch and must be handled separately.
#[cfg(target_os = "windows")]
fn verify_sha256_ps(file_path: &std::path::Path, expected_sha256: &str) -> anyhow::Result<bool> {
    let escaped = ps_escape(file_path);
    let cmd = format!(
        "(Get-FileHash -Path '{}' -Algorithm SHA256).Hash.ToLower()",
        escaped
    );
    let output = crate::binary::run_powershell_capture(
        &["-NoProfile", "-Command", &cmd],
        std::time::Duration::from_secs(120),
    )?;
    if !output.status.success() {
        return Ok(false);
    }
    let actual = String::from_utf8_lossy(&output.stdout).trim().to_string();
    Ok(actual == expected_sha256)
}

/// Runs the Windows VM provisioning sequence: WSL availability + auto-install,
/// `.wslconfig` VPN-compat keys, distro import/verify, nerdctl-full install.
#[cfg(target_os = "windows")]
pub fn init_vm_windows() -> anyhow::Result<()> {
    use crate::runtime::decode_wsl_output;

    // OS prerequisite check (SSOT: os_prereqs module)
    let violations = crate::os_prereqs::check_os_prereqs();
    if !violations.is_empty() {
        // WSL not available — attempt auto-install (always bails: restart or failure)
        attempt_wsl_install()?;
    }

    // Enable WSL2 mirrored networking before any distro starts; non-fatal.
    if let Err(e) = ensure_wslconfig_vpn_compat() {
        log::warn!("failed to ensure .wslconfig VPN compatibility (non-fatal): {e}");
    }

    let list = crate::binary::system_command("wsl.exe")
        .args(["--list", "--quiet"])
        .output()?;
    // Decode WSL output — wsl.exe often outputs UTF-16LE on Windows
    let list_str = decode_wsl_output(&list.stdout);
    let distro_exists = list_str
        .lines()
        .any(|l| l.trim().trim_matches('\0') == consts::wsl_distro_name());

    if !distro_exists {
        import_wsl_distro()?;
    } else {
        verify_wsl_distro_origin()?;
    }

    install_nerdctl_full()?;

    Ok(())
}

/// Writes/updates `%USERPROFILE%\.wslconfig` so `[wsl2]` declares `networkingMode=mirrored`,
/// `dnsTunneling=true`, `autoProxy=true` (Win11 22H2+); preserves other keys; missing → skeleton.
#[cfg(target_os = "windows")]
pub fn ensure_wslconfig_vpn_compat() -> anyhow::Result<()> {
    let home = dirs::home_dir()
        .ok_or_else(|| anyhow::anyhow!("cannot determine %USERPROFILE% for .wslconfig"))?;
    let path = home.join(".wslconfig");
    let existing = read_existing_wslconfig(std::fs::read_to_string(&path), &path)?;
    let updated = merge_wslconfig_vpn_keys(&existing);
    if updated != existing {
        // Shared write: the WSL service must read this file — an owner-only
        // protected DACL breaks it ("access denied" in non-user contexts).
        crate::fs_perms::write_shared_file_atomic(&path, &updated)?;
        log::info!("wrote VPN-compatible [wsl2] keys to {}", path.display());
        // .wslconfig is read only on WSL2 boot; new keys need `wsl --shutdown`.
        log::warn!(
            ".wslconfig changed — run `wsl --shutdown` from PowerShell to \
             activate mirrored-mode networking (required to reach \
             services on a corporate VPN from inside Speedwave's WSL distro)"
        );
    }
    heal_wslconfig_dacl(&path);
    Ok(())
}

/// Resets a legacy owner-only protected DACL on `.wslconfig` back to the
/// inherited profile ACL (earlier releases tightened it). Warn-only.
#[cfg(target_os = "windows")]
fn heal_wslconfig_dacl(path: &std::path::Path) {
    if !path.exists() {
        return;
    }
    let icacls = std::path::PathBuf::from(
        std::env::var_os("SystemRoot").unwrap_or_else(|| std::ffi::OsString::from(r"C:\Windows")),
    )
    .join("System32")
    .join("icacls.exe");
    match crate::binary::system_command(&icacls.to_string_lossy())
        .args([path.as_os_str(), std::ffi::OsStr::new("/reset")])
        .output()
    {
        Ok(o) if o.status.success() => {}
        Ok(o) => log::warn!(
            ".wslconfig DACL reset failed (non-fatal): {}",
            String::from_utf8_lossy(&o.stderr).trim()
        ),
        Err(e) => log::warn!(".wslconfig DACL reset spawn failed (non-fatal): {e}"),
    }
}

/// Classifies a `.wslconfig` read: only `NotFound` maps to empty (fresh
/// skeleton); any other failure (UTF-16, EACCES, EBUSY) bails.
#[cfg(any(target_os = "windows", test))]
pub fn read_existing_wslconfig(
    read: std::io::Result<String>,
    path: &std::path::Path,
) -> anyhow::Result<String> {
    match read {
        Ok(content) => Ok(content),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
        Err(e) => Err(anyhow::anyhow!(e).context(format!(
            "cannot read {} (e.g. UTF-16 from PowerShell Out-File, locked, or no permission); \
             refusing to overwrite global [wsl2] settings — fix or delete .wslconfig and retry",
            path.display()
        ))),
    }
}

/// Pure transform: takes existing `.wslconfig` content (may be empty), returns a version with the
/// three VPN-compat keys inserted/updated under `[wsl2]`; other sections preserved. Idempotent.
#[cfg(any(target_os = "windows", test))]
pub fn merge_wslconfig_vpn_keys(input: &str) -> String {
    const VPN_KEYS: &[(&str, &str)] = &[
        ("networkingMode", "mirrored"),
        ("dnsTunneling", "true"),
        ("autoProxy", "true"),
    ];

    // Match the dominant line ending of the input — `.wslconfig` from Notepad is CRLF; bare LF
    // for new keys yields a mixed-ending file (tolerated by WSL but cosmetically ugly).
    let nl = if input.contains("\r\n") { "\r\n" } else { "\n" };

    let mut out = String::with_capacity(input.len() + 128);
    let mut current_section: Option<String> = None;
    let mut wsl2_seen = false;
    let mut wsl2_key_present: std::collections::HashSet<String> = Default::default();
    let mut pending_inject: Vec<String> = Vec::new();

    let push_missing_keys = |present: &std::collections::HashSet<String>,
                             pending: &mut Vec<String>| {
        for (k, v) in VPN_KEYS {
            if !present.contains(&k.to_ascii_lowercase()) {
                pending.push(format!("{k}={v}{nl}"));
            }
        }
    };

    for line in input.split_inclusive('\n') {
        let trimmed = line.trim();
        if let Some(stripped) = trimmed.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            if current_section.as_deref() == Some("wsl2") {
                push_missing_keys(&wsl2_key_present, &mut pending_inject);
                for inj in pending_inject.drain(..) {
                    out.push_str(&inj);
                }
            }
            current_section = Some(stripped.trim().to_ascii_lowercase());
            if current_section.as_deref() == Some("wsl2") {
                wsl2_seen = true;
            }
            out.push_str(line);
            continue;
        }
        if current_section.as_deref() == Some("wsl2") {
            if let Some(eq) = trimmed.find('=') {
                let key = trimmed[..eq].trim().to_ascii_lowercase();
                if let Some((_, desired_val)) =
                    VPN_KEYS.iter().find(|(k, _)| k.eq_ignore_ascii_case(&key))
                {
                    let original_key = trimmed[..eq].trim_end();
                    out.push_str(&format!("{original_key}={desired_val}{nl}"));
                    wsl2_key_present.insert(key);
                    continue;
                }
                wsl2_key_present.insert(key);
            }
        }
        out.push_str(line);
    }

    if current_section.as_deref() == Some("wsl2") {
        push_missing_keys(&wsl2_key_present, &mut pending_inject);
        if !out.ends_with('\n') && !pending_inject.is_empty() {
            out.push_str(nl);
        }
        for inj in pending_inject {
            out.push_str(&inj);
        }
    } else if !wsl2_seen {
        if !out.is_empty() && !out.ends_with('\n') {
            out.push_str(nl);
        }
        if !out.is_empty() {
            out.push_str(nl);
        }
        out.push_str(&format!("[wsl2]{nl}"));
        for (k, v) in VPN_KEYS {
            out.push_str(&format!("{k}={v}{nl}"));
        }
    }

    out
}

/// Verifies an existing WSL2 distro [`consts::wsl_distro_name`] was created by Speedwave by
